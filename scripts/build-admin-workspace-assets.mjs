import { readFile, readdir, writeFile } from 'node:fs/promises';
import { ROUTES, rewriteNavigation } from '../deployment/admin-workspace/routes.mjs';
const root=new URL('../',import.meta.url);
const read=async path=>(await readFile(new URL(path,root),'utf8')).replace(/\r\n/g,'\n');
const assets={};
for(const route of ROUTES){
  let file;
  if(route.kind==='command') file='site/static/admin/command-center.html';
  if(route.kind==='blog') file='site/static/admin/blog.html';
  if(route.kind==='static') file='site/static'+route.legacy+'.html';
  if(route.kind==='ops') file='site/static/ops/index.html';
  if(!file) continue;
  let body=await read(file);
  if(route.kind==='command') body=body.replace('data-view="dashboard"','data-view="'+route.view+'"');
  if(route.kind==='blog') body=body.replace('function getBlogPage() {','function getBlogPage() { return '+JSON.stringify(route.view)+';');
  if(route.kind==='ops') body=body.replace("'更新 '+(d.generated_at", "'保存時点の記録 '+(d.generated_at");
  assets[route.path]={body:rewriteNavigation(body),type:'text/html; charset=utf-8'};
}
for(const name of ['command-center.css','command-center.js','sns-metrics.js']){
  assets['/admin/'+name]={body:rewriteNavigation(await read('site/static/admin/'+name)),type:name.endsWith('.css')?'text/css; charset=utf-8':'text/javascript; charset=utf-8'};
}
const docs=[];
const excluded=[];
for(const file of (await readdir(new URL('content/consul-work/',root))).filter(f=>f.endsWith('.md')).sort()){
  const raw=await read('content/consul-work/'+file);
  if(/(?:sk-(?:proj-)?[A-Za-z0-9_-]{30,}|ghp_[A-Za-z0-9]{30,}|AKIA[A-Z0-9]{16})/.test(raw)) { excluded.push(file); continue; }
  const body=raw.replace(/^---\n[\s\S]*?\n---\n/,'');
  const title=raw.match(/^title:\s*["']?(.+?)["']?$/m)?.[1] || body.match(/^#\s+(.+)$/m)?.[1] || file;
  docs.push({slug:file.slice(0,-3),filename:file,title,date:file.match(/^\d{4}-\d{2}-\d{2}/)?.[0]||'',category:'運用記録',body});
}
docs.sort((a,b)=>b.date.localeCompare(a.date));
let status=null;
try { status=JSON.parse(await read('outputs/agents_status.json')); } catch(error) { if(error.code!=='ENOENT') throw error; }
await writeFile(new URL('deployment/admin-workspace/assets.generated.mjs',root),'// Generated by scripts/build-admin-workspace-assets.mjs. Private Worker assets only.\nexport const assets='+JSON.stringify(assets)+';\nexport const documents='+JSON.stringify(docs)+';\nexport const statusSnapshot='+JSON.stringify(status)+';\n');
console.log(JSON.stringify({assets:Object.keys(assets).length,documents:docs.length,statusSnapshot:!!status,excludedCredentialLikeDocuments:excluded}));
